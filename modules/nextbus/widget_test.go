func TestStrTimeToInt(t *testing.T) {
	tests := []struct {
		name    string
		minutes string
		seconds string
		want    string
	}{
		{"zero values", "0", "0", "00:00"},
		{"whole minutes", "5", "300", "05:00"},
		{"minutes and seconds", "3", "195", "03:15"},
		{"single digit seconds", "1", "65", "01:05"},
		{"large values", "45", "2730", "45:30"},
		{"empty strings default to zero", "", "", "00:00"},
		{"non-numeric defaults to zero", "abc", "xyz", "00:00"},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := strTimeToInt(tt.minutes, tt.seconds)
			if got != tt.want {
				t.Errorf("strTimeToInt(%q, %q) = %q, want %q", tt.minutes, tt.seconds, got, tt.want)
			}
		})
	}
}

func TestGetNextBus_ArrayResponse(t *testing.T) {
	response := AutoGenerated{
		Copyright: "test",
		Predictions: Predictions{
			RouteTag:    "N",
			StopTag:     "5678",
			RouteTitle:  "N-Judah",
			AgencyTitle: "SF Muni",
			StopTitle:   "Duboce & Church",
			Direction: Direction{
				Title:         "Outbound",
				PredictionRaw: json.RawMessage(`[{"minutes":"5","seconds":"300","tripTag":"1","isDeparture":"false","block":"1","dirTag":"out","branch":"N","epochTime":"123","vehicle":"v1","affectedByLayover":"false"},{"minutes":"12","seconds":"735","tripTag":"2","isDeparture":"false","block":"2","dirTag":"out","branch":"N","epochTime":"456","vehicle":"v2","affectedByLayover":"false"}]`),
			},
		},
	}

	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Query().Get("a") != "sf-muni" {
			t.Errorf("expected agency sf-muni, got %s", r.URL.Query().Get("a"))
		}
		if r.URL.Query().Get("r") != "N" {
			t.Errorf("expected route N, got %s", r.URL.Query().Get("r"))
		}
		if r.URL.Query().Get("stopId") != "5678" {
			t.Errorf("expected stopId 5678, got %s", r.URL.Query().Get("stopId"))
		}
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(response)
	}))
	defer server.Close()

	origURL := baseURL
	baseURL = server.URL
	defer func() { baseURL = origURL }()

	result := getNextBus("sf-muni", "N", "5678")

	expected := "N-Judah | ETA [05:00]\nN-Judah | ETA [12:15]\n"
	if result != expected {
		t.Errorf("getNextBus array response:\ngot:  %q\nwant: %q", result, expected)
	}
}

