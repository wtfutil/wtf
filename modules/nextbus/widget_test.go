func TestGetNextBus_InvalidPredictionRaw(t *testing.T) {
	// PredictionRaw is neither a valid object nor array
	response := AutoGenerated{
		Predictions: Predictions{
			RouteTitle: "Test Route",
			Direction: Direction{
				PredictionRaw: json.RawMessage(`"invalid"`),
			},
		},
	}

	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(response)
	}))
	defer server.Close()

	origURL := baseURL
	baseURL = server.URL
	defer func() { baseURL = origURL }()

	result := getNextBus("sf-muni", "N", "1234")
	// When parseType is empty string (neither "array" nor "object"), falls through to the else branch
	// with zero-value nextBusObject
	expected := "Test Route | ETA [00:00]\n"
	if result != expected {
		t.Errorf("expected fallback formatting, got: %q", result)
	}
}

