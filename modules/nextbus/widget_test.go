func TestGetNextBus_HTTPError(t *testing.T) {
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		// Close connection immediately to trigger HTTP error
		hj, ok := w.(http.Hijacker)
		if !ok {
			t.Fatal("server doesn't support hijacking")
		}
		conn, _, _ := hj.Hijack()
		_ = conn.Close()
	}))
	defer server.Close()

	origURL := baseURL
	baseURL = server.URL
	defer func() { baseURL = origURL }()

	result := getNextBus("sf-muni", "N", "1234")
	if result != "[nextbus] error calling umoiq" {
		t.Errorf("expected HTTP error message, got: %q", result)
	}
}

