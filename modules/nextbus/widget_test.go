func TestNewSettingsFromYAML(t *testing.T) {
	yamlStr := `
route: "N"
agency: "sf-muni"
stopID: "15678"
enabled: true
position:
  top: 0
  left: 0
  height: 1
  width: 1
refreshInterval: 300
`
	globalStr := `
wtf:
  colors:
    border:
      focusable: "darkslateblue"
      focused: "orange"
      normal: "gray"
`

	yamlConfig, err := config.ParseYaml(yamlStr)
	if err != nil {
		t.Fatalf("failed to parse yaml: %v", err)
	}

	globalConfig, err := config.ParseYaml(globalStr)
	if err != nil {
		t.Fatalf("failed to parse global yaml: %v", err)
	}

	settings := NewSettingsFromYAML("nextbus", yamlConfig, globalConfig)

	if settings.route != "N" {
		t.Errorf("expected route='N', got %q", settings.route)
	}
	if settings.agency != "sf-muni" {
		t.Errorf("expected agency='sf-muni', got %q", settings.agency)
	}
	if settings.stopID != "15678" {
		t.Errorf("expected stopID='15678', got %q", settings.stopID)
	}
	if settings.common == nil {
		t.Error("expected common settings to be non-nil")
	}
}

